using Content.Client._Floof.Consent.Systems;
using Content.Client.UserInterface.Controls;
using Content.Shared._Floof.Consent;
using Content.Shared._Floof.Consent.Prototypes;
using Content.Shared.CCVar;
using Content.Shared.Ghost.Components;
using Robust.Client.AutoGenerated;
using Robust.Client.Player;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Configuration;
using Robust.Shared.Prototypes;

namespace Content.Client._Floof.Consent.UI.Windows;

/// <summary>
///     In-round editor for the consent text and toggles of the player's current body, same as the character editor's consent tab.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class ConsentWindow : FancyWindow
{
    [Dependency] private IConfigurationManager _configManager = default!;
    [Dependency] private IEntityManager _entityManager = default!;
    [Dependency] private IPlayerManager _playerManager = default!;

    public ConsentWindow()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        SaveConsentSettings.OnPressed += _ =>
        {
            SaveConsentSettings.Disabled = true;
            SaveLabel.Text = "";
            _entityManager.System<ConsentSystem>().RequestUpdate(ConsentEditor.Text, ConsentEditor.Toggles);
        };

        ConsentEditor.OnConsentTextChanged += _ => UnsavedChanges();
        ConsentEditor.OnConsentToggleChanged += (_, _) => UnsavedChanges();
    }

    private void UnsavedChanges()
    {
        var maxLength = _configManager.GetCVar(CCVars.MaxConsentTextLength);
        var length = ConsentEditor.Text.Length;

        if (length > maxLength)
        {
            SaveLabel.Text = Loc.GetString("consent-window-char-limit-warning", ("length", length), ("maxLength", maxLength));
            SaveConsentSettings.Disabled = true;

            return;
        }

        SaveLabel.Text = Loc.GetString("consent-window-unsaved-changes");
        SaveConsentSettings.Disabled = false;
    }

    /// <summary>
    ///     Loads the consent of the player's current body, discarding unsaved changes.
    /// </summary>
    public void UpdateUi()
    {
        var entity = _playerManager.LocalEntity;
        var editable = entity != null && !_entityManager.HasComponent<GhostComponent>(entity);

        var text = _entityManager.TryGetComponent<ConsentExaminableComponent>(entity, out var examinable) ? examinable.Content : "";
        var toggles = _entityManager.TryGetComponent<ConsentTogglesComponent>(entity, out var comp)
            ? comp.Toggles
            : new HashSet<ProtoId<ConsentTogglePrototype>>();

        ConsentEditor.SetConsent(editable ? text : "", toggles);
        ConsentEditor.SetEditable(editable);

        SaveConsentSettings.Disabled = true;
        SaveLabel.Text = editable ? "" : Loc.GetString("consent-window-no-body");
    }
}
