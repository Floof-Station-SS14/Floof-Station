using System.Linq;
using Content.Shared._Floof.Consent.Prototypes;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Prototypes;
using Robust.Shared.Utility;

namespace Content.Client._Floof.Consent;

/// <summary>
///     Consent text and toggles editor, used by the character editor and the in-round consent window.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class NewConsentText : Control
{
    [Dependency] private IPrototypeManager _prototype = default!;

    private readonly Dictionary<ProtoId<ConsentTogglePrototype>, CheckBox> _toggleBoxes = new();

    public Action<string>? OnConsentTextChanged;
    public Action<ProtoId<ConsentTogglePrototype>, bool>? OnConsentToggleChanged;

    public NewConsentText()
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        CConsentTextInput.Placeholder = new Rope.Leaf(Loc.GetString("consent-window-freetext-placeholder"));
        CConsentTextInput.OnTextChanged += _ => OnConsentTextChanged?.Invoke(Text);

        foreach (var toggle in _prototype.EnumeratePrototypes<ConsentTogglePrototype>().OrderBy(t => Loc.GetString(t.Name)))
        {
            var box = new CheckBox
            {
                Text = Loc.GetString(toggle.Name),
                ToolTip = Loc.GetString(toggle.Description),
            };
            var id = new ProtoId<ConsentTogglePrototype>(toggle.ID);
            box.OnToggled += args => OnConsentToggleChanged?.Invoke(id, args.Pressed);
            _toggleBoxes[id] = box;
            CConsentToggles.AddChild(box);
        }
    }

    public string Text => Rope.Collapse(CConsentTextInput.TextRope).Trim();

    public HashSet<ProtoId<ConsentTogglePrototype>> Toggles =>
        _toggleBoxes.Where(kv => kv.Value.Pressed).Select(kv => kv.Key).ToHashSet();

    public void SetConsent(string text, IReadOnlySet<ProtoId<ConsentTogglePrototype>> toggles)
    {
        CConsentTextInput.TextRope = new Rope.Leaf(text);

        foreach (var (id, box) in _toggleBoxes)
        {
            box.Pressed = toggles.Contains(id);
        }
    }

    public void SetEditable(bool editable)
    {
        CConsentTextInput.Editable = editable;

        foreach (var box in _toggleBoxes.Values)
        {
            box.Disabled = !editable;
        }
    }
}
