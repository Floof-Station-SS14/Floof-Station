using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client.Communications.UI.Widgets;

/// <summary>
/// A set of controls to request or return the emergency (evac) shuttle.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class ShuttleControls : Control
{
    [Dependency] private IGameTiming _timing = default!;

    private bool _canCall;
    private bool _countdownStarted;
    private TimeSpan? _countdownEnd;

    public event Action? OnShuttleCalled;
    public event Action? OnShuttleRecalled;

    public ShuttleControls()
    {
        IoCManager.InjectDependencies(this);
        RobustXamlLoader.Load(this);

        EmergencyShuttleCallButton.OnPressed += _ => OnShuttleCalled?.Invoke();
        EmergencyShuttleRecallButton.OnPressed += _ => OnShuttleRecalled?.Invoke();
        SyncButtonState();
    }

    public void UpdateState(bool canCallShuttle, bool countdownStarted, TimeSpan? expectedCountdownEnd)
    {
        _canCall = canCallShuttle;
        _countdownStarted = countdownStarted;
        _countdownEnd = expectedCountdownEnd;
        SyncButtonState();
    }

    // Floof Section - Flooding
    public void SetResurface()
    {
        HeaderLabel.Text = Loc.GetString("comms-console-resurface-header");
        StatusLabel.Text = Loc.GetString("comms-console-resurface-status");
        EmergencyShuttleCallButton.Text = Loc.GetString("comms-console-resurface-button");
        EmergencyShuttleRecallButton.Text = Loc.GetString("comms-console-resurface-abort-button");
        DepthLabel.Visible = true;
    }

    public bool CountdownStarted => _countdownStarted;

    private bool _diving;
    private TimeSpan? _diveLeft;

    /// <param name="left">Time shown on the display, or null if nothing is counting down.</param>
    public void SetDiveStatus(string status, TimeSpan? left)
    {
        _diving = true;
        _diveLeft = left;
        StatusLabel.Text = status;
    }

    public void SetResurfaceCountdown()
    {
        _diving = false;
        StatusLabel.Text = Loc.GetString("comms-console-resurface-status");
    }

    public void SetDepth(int? meters)
    {
        DepthLabel.Text = meters is { } value
            ? Loc.GetString("comms-console-resurface-depth", ("meters", value))
            : Loc.GetString("comms-console-resurface-depth-surface");
    }
    // Floof Section End

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdateCountdown();
    }

    /// <summary>
    /// Syncs and animates the display of the time-to-shuttle-arrival label
    /// </summary>
    private void UpdateCountdown()
    {
        // Floof Section - Flooding
        if (_diving)
        {
            if (_diveLeft is not { } left)
            {
                CountdownLabel.Text = "--:--";
                return;
            }

            var seconds = (int) Math.Ceiling(Math.Max(left.TotalSeconds, 0));
            CountdownLabel.Text = (seconds / 60).ToString("D2") + ":" + (seconds % 60).ToString("D2");
            return;
        }
        // Floof Section End

        // Set the label on the LCD countdown
        var countdown = _countdownEnd == null ? 0.0f : (float)Math.Max(_countdownEnd.Value.Subtract(_timing.CurTime).TotalSeconds, 0);

        var remainingWholeSeconds = _countdownStarted ? (int)Math.Ceiling(countdown) : 0;
        var message = (remainingWholeSeconds / 60).ToString("D2") + ":" + (remainingWholeSeconds % 60).ToString("D2");
        CountdownLabel.Text = message;
    }

    /// <summary>
    /// Configure the shuttle call/recall buttons to have a consistent state
    /// </summary>
    private void SyncButtonState()
    {
        EmergencyShuttleCallButton.Disabled = !(_canCall && !_countdownStarted);
        EmergencyShuttleRecallButton.Disabled = !(_canCall && _countdownStarted);
    }
}
